const fs=require('fs');const dir=__dirname;
const seed=fs.readFileSync(dir+'/StockRows.sql','utf8').replaceAll('Mas_Stock','#Stock');
let s=`SET NOCOUNT ON; SET XACT_ABORT ON;
SELECT TOP (0) * INTO #Stock FROM dbo.Mas_Stock;
DECLARE @AllowNegativeStock varchar(10)='Y', @Times int=1, @GDCode varchar(10)='TEST';
`;
const fields={strEntType:'SAL',StrSysProdCode:'123',StrBatch:"A'B",StrMRP:'99.50',StrExpDt:'',StrMfgDt:'',StrPRate:'70',StrSRate:'80',StrBoxPack:'12',StrInBoxPack:'1',StrFrQty:'0',StrFrBatch:'FREE',StrFrMrp:'0',StrFrExpDt:'',StrFrMfgdt:''};
for(const [n,v] of Object.entries(fields))s+=`DECLARE @${n} varchar(max)='${v.replaceAll("'","''").padEnd(v.length+20-v.length+(v.includes("'")?1:0),' ')}';\n`;
// Each seed batch needs its own variable scope.
const params=['AllowNegativeStock','Times','GDCode',...Object.keys(fields)];
const def=params.map(n=>'@'+n+' '+(n==='Times'?'int':'varchar(max)')).join(',');
const run=`EXEC sp_executesql N'${seed.replaceAll("'","''")}', N'${def}', ${params.map(n=>'@'+n).join(',')};\n`;
s+=`BEGIN TRAN;\n`+run+`IF (SELECT COUNT(*) FROM #Stock)<>1 THROW 50000,'Missing key not inserted',1;
IF NOT EXISTS(SELECT 1 FROM #Stock WHERE MRP=99.50 AND Batch='A''B' AND Qty=0 AND IsLocked='N') THROW 50000,'Incorrect seeded values',1;
UPDATE #Stock SET Qty=Qty-5;
`+run+`IF (SELECT COUNT(*) FROM #Stock)<>1 OR (SELECT Qty FROM #Stock)<>-5 THROW 50000,'Existing stock changed',1;
SET @GDCode='SECOND';
`+run+`IF (SELECT COUNT(*) FROM #Stock)<>2 THROW 50000,'Godown key mismatch',1;
SET @StrMRP=LEFT('0'+SPACE(20),20); SET @StrFrQty=LEFT('2'+SPACE(20),20);
`+run+`IF (SELECT COUNT(*) FROM #Stock)<>4 THROW 50000,'Zero MRP or free stock missing',1;
SET @StrBatch=LEFT('SKIPPED'+SPACE(20),20); SET @strEntType=LEFT('GDR'+SPACE(20),20);
`+run+`IF (SELECT COUNT(*) FROM #Stock)<>4 THROW 50000,'Return path changed',1;
SET @strEntType=LEFT('SAL'+SPACE(20),20); SET @AllowNegativeStock='N';
`+run+`IF (SELECT COUNT(*) FROM #Stock)<>4 THROW 50000,'Negative disabled path changed',1;
ROLLBACK;
IF EXISTS(SELECT 1 FROM #Stock) THROW 50000,'Rollback left stock rows',1;
PRINT 'PASS: missing/zero MRP, quoted batch, duplicate preservation, negative deduction, godown, free stock, return bypass, setting bypass, rollback.';
`;
fs.writeFileSync(dir+'/Checks.sql',s);
